def photo(key, cls=''):
    if key in PHOTOS:
        src, alt = PHOTOS[key]
        cls_attr = f' class="{cls}"' if cls else ''
        return f'<img src="/{src}" alt="{e(alt)}" loading="lazy" width="800" height="600"{cls_attr}>'
    return f'<div class="ph">TODO: photo — {e(key.replace("-", " "))}</div>'


def fmt_time(t):
    h, m = map(int, t.split(':'))
    return f"{h % 12 or 12}{f':{m:02d}' if m else ''}{'am' if h < 12 else 'pm'}"


def day_date(iso):
    d = dt.date.fromisoformat(iso)
    return f"{d.strftime('%a')} {d.day} {d.strftime('%b')}"


def rm(n):
    return f'RM{n:,.0f}' if isinstance(n, (int, float)) else ''


def teacher_for(key):
    t = [x for x in TEACHERS if key in x.get('teaches', [])]
    return ' or '.join(x['name'] or x['role'] for x in t) or 'TODO: teacher'


