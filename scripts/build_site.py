def consent_kind(s):
    f = FORMATS[s['format']]
    if f['discipline'] == 'baking':
        return 'baking'
    if 'kid' in (f.get('audience') or '') or s['format'] in ('kids-art-studio', 'parent-child-studio'):
        return 'child'
    return 'adult'


