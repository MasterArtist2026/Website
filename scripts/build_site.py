def PriceTable(voice):
    if voice == 'academy':
        rows = []
        for p in CL['programmes']:
            if p.get('status') == 'paused':
                continue
            if 'price_month' in p:
                price = f"{rm(p['price_month'])}/month"
                extra = f"{rm(p['per_session'])} per session"
                if p.get('group_price_month'):
                    extra += f" · group {rm(p['group_price_month'])}/month · adults {rm(p['adult_price_month'])}/month"
                if p.get('sibling_or_student_price'):
                    extra += f" · sibling or student {rm(p['sibling_or_student_price'])}/month"
            else:
                price, extra = rm(p['price_course']), f"6 weeks · {rm(p['price_at_bake_lab'])} if you book at a Bake Lab"
            rows.append(f'<tr><td><a href="/classes/{p["id"]}/">{e(p["name"])}</a></td><td class="muted">{e(extra)}</td><td class="num">{price}</td></tr>')
        t = CL['trial']
        note = f'<p class="price-note">Start with a {rm(t["price"])} trial, {e(t["note"])}. Siblings {int(CL["discounts"]["sibling"] * 100)}% off.</p>'
        return f'<div class="v-academy"><table class="price-table"><caption>Academy · weekly classes</caption><thead><tr><th>Programme</th><th>Details</th><th>Price</th></tr></thead><tbody>{"".join(rows)}</tbody></table>{note}</div>'
    rows = []
    for f in WS['formats']:
        if f.get('type') in ('class', 'course'):
            continue
        if f.get('bundle'):
            price, extra = rm(f['bundle']['price']), f"Family Sunday: {f['bundle']['includes']} · extra child {rm(f['bundle']['extra_child'])}"
        else:
            price = rm(f['price']) + (f" {f['price_unit']}" if f.get('price_unit') else '')
            extra = ' · '.join(x for x in [f"pair {rm(f['pair_price'])}" if f.get('pair_price') else '',
                                            f"specialty {rm(f['price_specialty'])}" if f.get('price_specialty') else '',
                                            f"{f['duration_min'] // 60}h{f['duration_min'] % 60:02d}".replace('h00', 'h')] if x)
        rows.append(f'<tr><td><a href="/workshops/{f["id"]}/">{e(f["name"])}</a></td><td class="muted">{e(extra)}</td><td class="num">{e(price)}</td></tr>')
    pw = WS['policies']['pricing_window']
    until = dt.date.fromisoformat(pw['until'])
    note = (f'<p class="price-note">{e(pw["name"])} prices until {until.day} {until.strftime("%B %Y")}. '
            f'Dine + workshop {rm(WS["addons"]["dine"]["price_per_person"])} a person. Minimum {WS["policies"]["minimum_to_run"]} to run.</p>')
    return f'<div class="v-studio"><table class="price-table"><caption>Studio Sessions · workshops</caption><thead><tr><th>Workshop</th><th>Details</th><th>Price</th></tr></thead><tbody>{"".join(rows)}</tbody></table>{note}</div>'


