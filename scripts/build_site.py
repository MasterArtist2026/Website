ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / 'data'


def load(name):
    d = json.loads((DATA / name).read_text())
    return {k: v for k, v in d.items() if not k.startswith('_')} if isinstance(d, dict) else d


SITE = load('site.json')
WS = load('workshops.json')
CL = load('classes-seed.json')
TEACHERS = load('teachers.json')['teachers']
FORMATS = {f['id']: f for f in WS['formats']}
ROOMS = {r['name']: r for r in WS.get('rooms', [])}

e = lambda s: html.escape(str(s if s is not None else ''), quote=True)


def ver(path):
    return hashlib.sha1((ROOT / path).read_bytes()).hexdigest()[:8]


