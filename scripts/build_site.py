def WhatsAppButton(message, voice, label='WhatsApp us', cls='btn wa', fmt='', programme='', session='', trial=False):
    """Pre-filled WhatsApp link; {source} is filled in the browser from the visitor's UTM."""
    href = f"https://wa.me/{SITE['whatsapp']}?text={urllib.parse.quote(message.replace('{source}', 'site'))}"
    attrs = f' data-voice="{voice}" data-format="{e(fmt)}" data-programme="{e(programme)}" data-session="{e(session)}"'
    return (f'<a class="{cls}" href="{e(href)}" data-wa-msg="{e(message)}"{attrs}{" data-trial" if trial else ""} '
            f'target="_blank" rel="noopener">{WA_ICON}<span>{e(label)}</span></a>')


def wa_studio(s):
    return f"Hi, I'd like to book {s['name']} on {day_date(s['date'])} at {fmt_time(s['time'])}. Source: {{source}}."


def wa_trial(p):
    return f"Hi, I'd like to book the RM{CL['trial']['price']} trial for {p['name']}. Source: {{source}}."


def seats_html(s):
    if s['seats_left'] is None:
        return ''
    unit = s.get('cap_unit') or 'seats'
    if s['seats_left'] <= 0:
        return '<span class="seats out">Sold out</span>'
    cls = ' nearly' if s['seats_left'] < 6 else ''
    word = 'Nearly full · ' if cls else ''
    return f'<span class="seats{cls}">{word}{s["seats_left"]} of {s["cap"]} {unit} left</span>'


def SessionCard(s, link=True):
    """Studio Sessions card: photo · name · day/date/time · room · price (+pair) · seats · Book."""
    f = FORMATS[s['format']]
    if s.get('bundle'):
        price = f'<div class="price">{rm(s["price"])} <small>Family Sunday: one adult Textured Canvas + one child, same hour · extra child {rm(s["bundle"]["extra_child"])}</small></div>'
    else:
        unit = f' {s["price_unit"]}' if s.get('price_unit') else ''
        pair = f'<small>Pair {rm(s["pair_price"])}</small>' if s.get('pair_price') else ''
        price = f'<div class="price">{rm(s["price"])}{e(unit)} {pair}</div>'
    badges = []
    if s.get('dine'):
        badges.append('<span class="badge dine">Dine + workshop</span>')
    if s.get('variant') == 'specialty':
        badges.append('<span class="badge">Specialty bake</span>')
    title, theme = (s['theme'], f'<div class="sub">{e(s["name"])}</div>') if s.get('theme') else (s['name'], '')
    if s['seats_left'] == 0 and s.get('next_session'):
        nxt = next((x for x in WS['sessions'] if x['id'] == s['next_session']), None)
        action = f'<a class="btn ghost block" href="/workshops/{nxt["format"]}/{nxt["date"]}/">Sold out — next date {day_date(nxt["date"])}</a>' if nxt else ''
    else:
        action = f'<a class="btn block" href="/workshops/{s["format"]}/{s["date"]}/">Book</a>' if link else ''
    return f'''<article class="card v-studio">
  {photo(s['format'])}
  <div class="body">
    <h3>{e(title)}</h3>{theme}
    <div class="meta"><b>{day_date(s['date'])} · {fmt_time(s['time'])}–{fmt_time(s['end'])}</b><span>{e(s['room'])}</span></div>
    {price}
    <div class="badges">{' '.join(badges)} {seats_html(s)}</div>
    <div class="actions">{action}</div>
  </div>
</article>'''


